// 2. Crea una función que calcule el área de un rectángulo, tomando la base y la altura como parámetros
console.log('punto 2');
function calcularAreaRectangulo(
  base: number,
  altura: number,
):
  number {
  return base * altura;
}

console.log('area del triangulo', calcularAreaRectangulo(5, 10)); // Output: 50
